@pytest.fixture
def tiny_dataset(tmp_path: Path, monkeypatch) -> Path:
    """A 8-pair / 4-pair train/val dataset of *files*, registered like a real one.

    Content is random noise on purpose: a memorisable single pair would let the
    loss drop for reasons unrelated to the model being correct.
    """
    root = tmp_path / "data" / "Tiny"
    for split, n in (("train", 8), ("val", 4)):
        for mod in ("ir", "vi"):
            d = root / split / mod
            d.mkdir(parents=True)
            for i in range(n):
                g = torch.Generator().manual_seed(abs(hash((split, mod, i))) % 10_000)
                arr = (torch.rand(32, 40, generator=g) * 255).to(torch.uint8).numpy()
                if mod == "vi":
                    arr = np.repeat(arr[:, :, None], 3, axis=2)
                Image.fromarray(arr).save(d / f"{i:04d}.png")

    reg_dir = tmp_path / "registry"
    reg_dir.mkdir()
    (reg_dir / "Tiny.json").write_text(
        json.dumps({
            "dataset_id": "Tiny",
            "status": "ok",
            "root": str(root),
            "manifest_sha256": "0" * 64,
            "splits": {"train": 8, "val": 4},
            "retrieved_at": "1970-01-01T00:00:00Z",
            "notes": "generated by tests/test_engine.py; not a research dataset",
        })
    )
    monkeypatch.setattr("fusionedge.data.fusion_dataset.REGISTRY_DIR", reg_dir)
    return reg_dir


def _cfg(tmp_path: Path, model: str = "fusionedge", **train_over) -> dict:
    cfg = {
        "run_name": "engine_test",
        "seed": 7,
        "deterministic": True,
        "device": "cpu",
        "dataset": {"id": "Tiny", "train_split": "train", "eval_split": "val"},
        "model": {"name": model, "cfg": {"width": 8, "depth": 1}},
        "data": {"batch_size": 2, "num_workers": 0, "crop": 16},
        "train": {
            "epochs": 2, "lr": 1e-3, "optimizer": "adam", "scheduler": "none",
            "amp": False, "eval_every": 1, "grad_clip": 1.0, "best_metric": "MS_SSIM_ir",
            **train_over,
        },
        "loss": {"w_intensity": 1.0, "w_gradient": 1.0, "w_ssim": 1.0,
                 "w_edge": 1.0, "w_color": 1.0},
    }
    return cfg


