def tr_rows(path: Path):
    import csv

    with path.open(encoding="utf-8") as f:
        return list(csv.DictReader(f))


def test_resume_continues_from_the_saved_epoch(tmp_path, tiny_dataset):
    """Interrupt-and-resume must continue, not restart."""
    from fusionedge.data import load_registry as _lr

    run_dir = tmp_path / "run4"
    tr = Trainer(_cfg(tmp_path, epochs=2), run_dir, registry=_lr("Tiny"), device="cpu")
    tr.fit()
    assert tr.state.epoch == 2

    tr2 = Trainer(_cfg(tmp_path, epochs=4), run_dir, registry=_lr("Tiny"), device="cpu")
    tr2.load(run_dir / "checkpoints" / "last.pt")
    assert tr2.state.epoch == 2
    tr2.fit()
    assert tr2.state.epoch == 4
    assert len(tr_rows(run_dir / "metrics.csv")) == 4, "history must accumulate"


def test_saved_epoch_is_the_next_epoch_to_run(tmp_path, tiny_dataset):
    """`last.pt` stores epoch+1, so resuming continues instead of repeating the
    last epoch. If this regressed, resume would silently redo work."""
    from fusionedge.data import load_registry as _lr

    run_dir = tmp_path / "run4b"
    tr = Trainer(_cfg(tmp_path, epochs=2), run_dir, registry=_lr("Tiny"), device="cpu")
    tr.fit()
    payload = torch.load(run_dir / "checkpoints" / "last.pt", map_location="cpu",
                         weights_only=False)
    assert payload["epoch"] == 2, "checkpoint must record the next epoch index"


