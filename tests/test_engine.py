def test_benchmark_reports_latency_and_params(tmp_path):
    from fusionedge.engine.benchmark import benchmark_model

    m = build_model("fusionedge", {"width": 8, "depth": 1})
    res = benchmark_model(m, name="fusionedge", sizes=[[32, 32]], warmup=2, iters=5,
                          device="cpu")
    assert res["params"] > 0
    assert res["checkpoint_mb"] > 0
    lat = res["latency"][0]
    for k in ("latency_ms_median", "latency_ms_mean", "latency_ms_p95", "fps"):
        assert lat[k] > 0, f"{k} must be a positive measurement"
    assert lat["warmup_iters"] == 2 and lat["iters"] == 5


