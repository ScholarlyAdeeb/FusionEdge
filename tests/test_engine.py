def test_per_image_hook_is_called(tiny_dataset):
    _, val, _ = build_dataloaders("Tiny", batch_size=1, num_workers=0, crop=None)
    m = build_model("baseline", {"width": 8, "depth": 1})
    calls = []

    def hook(f, r, v):
        calls.append(1)
        return {"EXTRA": 1.0}

    res = evaluate_model(m, val, device=torch.device("cpu"), amp=False, per_image=hook)
    assert len(calls) == 4
    assert res["metrics"]["EXTRA"] == pytest.approx(1.0)


