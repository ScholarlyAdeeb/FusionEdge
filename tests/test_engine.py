"""Engine integration tests.

These run the *real* Trainer and evaluation path against a tiny dataset written
into a temporary directory and registered through the normal provenance
mechanism. That matters for two reasons:

  * it exercises the actual loader/trainer/checkpoint/eval code, not a mock;
  * it never touches the synthetic-data path (which is reserved for unit tests
    of tensor plumbing) and never writes into `experiments/`, so nothing here can
    be mistaken for a result. Assertions are about *mechanics* (does the loss
    go down, do files appear, does resume work), never about fusion quality.
"""

