def test_tensor_conversions():
    x = torch.rand(1, 3, 8, 8)
    u = tensor_to_uint8(x)
    assert u.shape == (8, 8, 3) and u.dtype == np.uint8
    assert u.max() <= 255
    g = tensor_to_uint8_gray(torch.rand(1, 1, 8, 8))
    assert g.shape == (8, 8) and g.dtype == np.uint8


def test_tensor_to_uint8_clamps_out_of_range():
    assert tensor_to_uint8(torch.tensor([[[[2.0, -1.0]]]])).max() == 255
    assert tensor_to_uint8(torch.tensor([[[[2.0, -1.0]]]])).min() == 0


def test_tensor_to_uint8_rejects_wrong_rank():
    with pytest.raises(ValueError):
        tensor_to_uint8(torch.rand(3, 8, 8))


def test_fuse_batch_handles_non_divisible_sizes():
    m = build_model("fusionedge", {"width": 8, "depth": 1}).eval()
    out = fuse_batch(m, torch.rand(1, 1, 37, 53), torch.rand(1, 3, 37, 53),
                     device=torch.device("cpu"), amp=False)
    assert out.shape == (1, 3, 37, 53)


def test_evaluate_model_returns_finite_metrics(tiny_dataset):
    _, val, _ = build_dataloaders("Tiny", batch_size=1, num_workers=0, crop=None)
    m = build_model("fusionedge", {"width": 8, "depth": 1})
    res = evaluate_model(m, val, device=torch.device("cpu"), amp=False)
    assert res["num_images"] == 4
    assert set(res["metrics"]) >= {"EN", "AG", "SF", "MS_SSIM_ir", "MS_SSIM_vi"}
    assert all(np.isfinite(v) for v in res["metrics"].values())
    assert len(res["per_image"]) == 4


