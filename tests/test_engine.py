@pytest.mark.parametrize("name", ["adam", "adamw", "sgd"])
def test_build_optimizer(name):
    m = build_model("fusionedge", {"width": 8, "depth": 1})
    opt = build_optimizer(m, {"optimizer": name, "lr": 1e-3})
    assert isinstance(opt, torch.optim.Optimizer)
    assert all(p["lr"] == 1e-3 for p in opt.param_groups)


def test_build_optimizer_rejects_unknown():
    with pytest.raises(KeyError):
        build_optimizer(build_model("fusionedge"), {"optimizer": "rmsprop_nope"})


def test_cosine_scheduler_decays_lr():
    m = build_model("fusionedge", {"width": 8, "depth": 1})
    opt = build_optimizer(m, {"optimizer": "adam", "lr": 1e-3})
    sch = build_scheduler(opt, {"scheduler": "cosine", "eta_min": 1e-6}, epochs=10)
    lrs = []
    for _ in range(10):
        lrs.append(opt.param_groups[0]["lr"])
        sch.step()
    assert lrs[0] > lrs[-1]
    assert lrs[-1] < 1e-4


def test_scheduler_none_is_allowed():
    m = build_model("fusionedge", {"width": 8, "depth": 1})
    opt = build_optimizer(m, {"optimizer": "adam"})
    assert build_scheduler(opt, {"scheduler": "none"}, epochs=5) is None


